// Writes docs/openapi.json and docs/postman.collection.json from the routes.
process.env.MONGODB_URI ||= 'mongodb://127.0.0.1/docs';
process.env.PUBLIC_API_URL = 'http://localhost:5001';
const { mkdir, writeFile } = await import('node:fs/promises');
const { api } = await import('../src/routes/index.js');
const { openApiDocument } = await import('../src/lib/openapi.js');
const { postmanCollection } = await import('./postman.js');

await mkdir('docs', { recursive: true });
await writeFile('docs/openapi.json', `${JSON.stringify(openApiDocument(), null, 2)}\n`);

// A readable list, split into website and admin panel. Duplicate "/admin/..." addresses are left out.
const isAlias = route => route.path.startsWith('/admin/deposits') || (route.path.startsWith('/admin/')
  && api.routes.some(other => other.method === route.method && other.path === route.path.slice('/admin'.length) && other.tag === route.tag));
const main = api.routes.filter(route => !isAlias(route));
await writeFile('docs/postman.collection.json', `${JSON.stringify(postmanCollection(main), null, 2)}\n`);
const open = route => !route.access || route.access === 'public';
const key = route => `${route.method.toUpperCase()} ${route.path}`;
// Addresses that staff and members share; the response depends on who is asking.
const shared = ['GET /members', 'GET /members/:id', 'GET /dashboard', 'POST /payments'];
const need = route => open(route) ? 'No login' : Array.isArray(route.access) ? `\`${route.access.join('.')}\``
  : { user: 'Login', member: 'Approved member', staff: 'Staff', superadmin: 'Super admin' }[route.access];
function tables(routes, access = need) {
  const groups = Map.groupBy(routes, route => route.tag);
  return [...groups].map(([tag, rows]) => `#### ${tag}\n\n| Method | Path | Purpose | Access |\n| --- | --- | --- | --- |\n${rows
    .map(route => `| ${route.method.toUpperCase()} | \`${route.path}\` | ${route.summary} | ${access(route)} |`).join('\n')}\n`).join('\n');
}
const account = main.filter(route => route.tag === 'Auth');
const visitor = main.filter(route => route.tag !== 'Auth' && open(route));
const member = main.filter(route => route.tag !== 'Auth' && (route.access === 'member' || ['/payments/mine', '/public/payment-submissions'].includes(route.path) || shared.includes(key(route))));
const admin = main.filter(route => Array.isArray(route.access) || ['staff', 'superadmin'].includes(route.access) || shared.includes(key(route)));
const memberAccess = route => key(route) === 'POST /payments' || route.path.startsWith('/payments/') || route.path.startsWith('/public/') ? 'Login' : 'Approved member';
const adminAccess = route => ({ 'GET /members': '`members.view`', 'GET /members/:id': '`members.view`', 'GET /dashboard': '`dashboard.view`', 'POST /payments': '`payments.create`' })[key(route)] || need(route);
await writeFile('docs/API-LIST.md', `# Bondhu Sanchay API list

Base address: \`http://localhost:5001/api/v1\`. Generated by \`npm run docs\`; do not edit by hand.

- [1. Public website](#1-public-website)
- [2. Account: website and admin panel](#2-account-website-and-admin-panel)
- [3. Admin panel](#3-admin-panel)

## 1. Public website

### Visitors (no login)

\`/public/investments\` and \`/public/projects\` return the same data. Also: \`GET /health\`, \`GET /ready\`, \`GET /openapi.json\`.

${tables(visitor)}
### Logged-in members

Staff with the dashboard permission can read these too.

${tables(member, memberAccess)}
## 2. Account: website and admin panel

${tables(account)}
## 3. Admin panel

Access \`module.action\` means a staff user needs that page and action. A super admin has all of them.
Most paths also work with an \`/admin\` prefix (for example \`/admin/members\`), and deposits are also at \`/admin/deposits\`.
\`/admin/payments\` is different from \`/payments\`: it lists member **submissions**.

${tables(admin, adminAccess)}`);
console.log(`Wrote docs for ${api.routes.length} routes. List: ${visitor.length} visitor, ${member.length} member, ${account.length} account, ${admin.length} admin.`);
const listed = new Set([...visitor, ...member, ...account, ...admin].map(key));
const missed = main.map(key).filter(name => !listed.has(name));
if (missed.length) console.log('Not listed:', missed);
